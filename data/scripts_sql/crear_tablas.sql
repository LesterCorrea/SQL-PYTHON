BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE MATRICULAS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE ALUMNOS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE CURSOS CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE DOCENTES CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE AULAS CASCADE CONSTRAINTS';
    
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
/

CREATE TABLE DOCENTES (
    ID_DOCENTE NUMBER(6) PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    ESPECIALIDAD VARCHAR2(40),
    EMAIL VARCHAR2(50)
);

CREATE TABLE AULAS (
    ID_AULA NUMBER(6) PRIMARY KEY,
    NOMBRE_AULA VARCHAR2(20),
    CAPACIDAD NUMBER(3)
);

CREATE TABLE CURSOS (
    ID_CURSO NUMBER(6) PRIMARY KEY,
    NOMBRE_CURSO VARCHAR2(50) NOT NULL,
    DURACION NUMBER(3), 
    ID_DOCENTE NUMBER(6),
    ID_AULA NUMBER(6),
    FOREIGN KEY (ID_DOCENTE) REFERENCES DOCENTES(ID_DOCENTE),
    FOREIGN KEY (ID_AULA) REFERENCES AULAS(ID_AULA)
);

CREATE TABLE ALUMNOS (
    ID_ALUMNO NUMBER(6) PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(60),
    FECHA_NAC DATE,
    EDAD NUMBER(2)
);

CREATE TABLE MATRICULAS (
    ID_MATRICULA NUMBER(6) PRIMARY KEY,
    ID_ALUMNO NUMBER(6),
    ID_CURSO NUMBER(6),
    FECHA_MATRICULA DATE DEFAULT SYSDATE,
    ESTADO VARCHAR2(20),
    FOREIGN KEY (ID_ALUMNO) REFERENCES ALUMNOS(ID_ALUMNO),
    FOREIGN KEY (ID_CURSO) REFERENCES CURSOS(ID_CURSO)
);

CREATE INDEX IDX_DOCENTE_EMAIL ON DOCENTES(EMAIL);
CREATE INDEX IDX_CURSO_NOMBRE ON CURSOS(NOMBRE_CURSO);
CREATE INDEX IDX_ALUMNO_EMAIL ON ALUMNOS(EMAIL);
CREATE INDEX IDX_MATRICULA_ESTADO ON MATRICULAS(ESTADO);

